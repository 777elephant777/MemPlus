package com.memplus.mixin.extras;

import com.memplus.core.MemPlusMixinPlugin;
import com.memplus.pool.StringDeduplicator;
import net.minecraft.world.level.ChunkPos;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfoReturnable;

/**
 * Targets ChunkPos - the chunk coordinate holder.
 *
 * <p>ChunkPos.toString() builds a fresh string each call via String.format
 * or similar. Across a busy server with thousands of chunk unloads/loads
 * and many logging calls, these strings are duplicated heavily. We dedup
 * the toString return so repeated logging of the same chunk shares one
 * String instance.
 */
@Mixin(value = ChunkPos.class, priority = 500)
public class ChunkPosMixin {

    @Inject(method = "toString", at = @At("RETURN"), cancellable = true, require = 0)
    private void memplus_dedupToString(CallbackInfoReturnable<String> cir) {
        if (!MemPlusMixinPlugin.interning()) return;
        String original = cir.getReturnValue();
        if (original != null && original.length() >= 8) {
            String canonical = StringDeduplicator.shared().dedup(original);
            if (canonical != original) {
                cir.setReturnValue(canonical);
            }
        }
    }
}
